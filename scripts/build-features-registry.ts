let md = `# KuraCode Feature Registry (Single Source of Truth)

**Product:** KuraCode | **Official Site:** https://www.genioussonu.me/extensions/kuracode
**Last Updated:** ${new Date().toISOString()}

---

## Status Summary

`;

const statusCounts: Record<string, number> = {};
for (const f of features) {
  statusCounts[f.status] = (statusCounts[f.status] || 0) + 1;
}

md += `| Status | Count |\n| :--- | :--- |\n`;
for (const [st, count] of Object.entries(statusCounts)) {
  md += `| **${st}** | ${count} |\n`;
}

md += `\n---\n\n## Feature Table\n\n`;
md += `| ID | Priority | Name | Surfaces | Status | Acceptance Criteria | Evidence | Last Verified |\n`;
md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;

for (const f of features) {
  const criteriaSummary = f.acceptanceCriteria.map((c) => c.replace(/\|/g, "\\|")).join("<br>");
  const evidenceSummary = f.evidence.length ? f.evidence.join(", ") : "—";
  const verified = f.lastVerified ?? "—";
  md += `| **${f.id}** | ${f.priority} | ${f.name} | ${f.surfaces.join(", ")} | \`${f.status}\` | ${criteriaSummary} | ${evidenceSummary} | ${verified} |\n`;
}

fs.writeFileSync(mdPath, md, "utf8");
